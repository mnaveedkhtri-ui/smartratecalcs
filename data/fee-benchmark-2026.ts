export function computeBenchmarkSample(record: FeeBenchmarkRecord, grossUsd: number) {
  const pctCut = grossUsd * (record.percentFee / 100);
  const spreadCut = grossUsd * (record.fxSpreadPct / 100);
  let totalFee = pctCut + spreadCut + record.fixedFeeUsd;
  if (record.minFeeUsd !== null && totalFee < record.minFeeUsd) {
    totalFee = record.minFeeUsd;
  }
  const rate = (record.percentFee + record.fxSpreadPct) / 100;
  const reverseGross = rate < 1 ? (grossUsd + record.fixedFeeUsd) / (1 - rate) : grossUsd;
  return {
    totalFeeUsd: Number(totalFee.toFixed(2)),
    netPayoutUsd: Number(Math.max(0, grossUsd - totalFee).toFixed(2)),
    effectiveTakeRatePct: Number(((totalFee / grossUsd) * 100).toFixed(2)),
    reverseGrossForTargetNetUsd: Number(reverseGross.toFixed(2)),
  };
}
